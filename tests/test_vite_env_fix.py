#!/usr/bin/env python3
"""FACTORY-VITE-ENV-FIX-V1 regression tests (stdlib only).

Defect: profiles/react-vite-supabase/scaffold failed `tsc` with TS2339 on `import.meta.env`
because no Vite client types were loaded. Fix: add scaffold/src/vite-env.d.ts.

What these tests prove (hermetic, no npm registry):
  * the materialized project contains src/vite-env.d.ts, recorded in provenance with its SHA-256;
  * the file references `vite/client` and types exactly the env vars that the scaffold uses / .env.example lists;
  * TYPE-LEVEL CAUSALITY with a control: compiling the generated src/lib/supabase.ts with `tsc --strict`
    -> WITHOUT the file: TS2339 on import.meta.env (defect reproduced);
    -> WITH the file:    no diagnostics at all.
    `vite/client` and `@supabase/supabase-js` are replaced by EMPTY/minimal local stubs so the result
    depends only on the scaffold's own declarations -- this is not a substitute for `npm ci && npm run build`
    of the generated project, which is recorded separately (requires registry access).
"""
import json
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from consumer import adapter as A  # noqa: E402

SCAFFOLD = ROOT / "profiles" / "react-vite-supabase" / "scaffold"
VITE_ENV = "src/vite-env.d.ts"


def golden():
    return json.loads((ROOT / "tests/fixtures/prompt-maker/golden-react-vite-supabase.json").read_text(encoding="utf-8"))


def tsc_cmd():
    exe = shutil.which("tsc")
    return [exe] if exe else None


def write_stubs(project):
    nm = project / "node_modules"
    (nm / "vite").mkdir(parents=True, exist_ok=True)
    (nm / "vite" / "package.json").write_text('{"name":"vite","version":"0.0.0-stub"}', encoding="utf-8")
    # deliberately EMPTY: the fix must not depend on what the real vite/client provides
    (nm / "vite" / "client.d.ts").write_text("export {};\n", encoding="utf-8")
    sb = nm / "@supabase" / "supabase-js"
    sb.mkdir(parents=True, exist_ok=True)
    (sb / "package.json").write_text('{"name":"@supabase/supabase-js","version":"0.0.0-stub","types":"index.d.ts"}', encoding="utf-8")
    (sb / "index.d.ts").write_text("export declare function createClient(url: string, key: string): unknown;\n", encoding="utf-8")


def typecheck(project, files):
    """Dedicated config (works on tsc 5.x and 6.x): the scaffold's strict options minus baseUrl/paths
    (aliases are irrelevant to supabase.ts; baseUrl is deprecated in tsc 6)."""
    cfg = {"compilerOptions": {"target": "ES2020", "lib": ["ES2020", "DOM"], "module": "ESNext",
                               "moduleResolution": "bundler", "skipLibCheck": True, "noEmit": True, "strict": True,
                               "isolatedModules": True, "types": []},
           "files": files}
    (project / "tsconfig.typecheck.json").write_text(json.dumps(cfg), encoding="utf-8")
    cmd = tsc_cmd() + ["-p", "tsconfig.typecheck.json", "--pretty", "false"]
    r = subprocess.run(cmd, cwd=project, capture_output=True, text=True)
    return r.returncode, (r.stdout + r.stderr)


class ViteEnvScaffoldTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.out = Path(self.tmp.name) / "proj"
        self.result = A.materialize(golden(), self.out, project_date="2026-10-11")

    def tearDown(self):
        self.tmp.cleanup()

    def test_file_generated_and_recorded_in_provenance(self):
        self.assertEqual(self.result["status"], "MATERIALIZED_AND_VALIDATED", self.result["validation"])
        self.assertTrue((self.out / VITE_ENV).is_file())
        prov = json.loads((self.out / A.PROVENANCE_FILE).read_text(encoding="utf-8"))
        self.assertIn(VITE_ENV, prov["files"])
        self.assertEqual(prov["files"][VITE_ENV], A.sha256_lf((self.out / VITE_ENV).read_bytes()))
        # template file has no tokens -> generated bytes equal the template bytes (LF-normalized)
        self.assertEqual(A.sha256_lf((SCAFFOLD / VITE_ENV).read_bytes()), prov["files"][VITE_ENV])

    def test_declares_vite_client_and_exactly_the_used_env_vars(self):
        decl = (self.out / VITE_ENV).read_text(encoding="utf-8")
        self.assertRegex(decl, r'^/// <reference types="vite/client" />', "must load Vite client types")
        declared = set(re.findall(r"readonly (VITE_[A-Z0-9_]+)\s*:", decl))
        used = set()
        for p in (self.out / "src").rglob("*"):
            if p.suffix in (".ts", ".tsx") and p.name != "vite-env.d.ts":
                used |= set(re.findall(r"import\.meta\.env\.(VITE_[A-Z0-9_]+)", p.read_text(encoding="utf-8")))
        example = set(re.findall(r"^(VITE_[A-Z0-9_]+)=", (self.out / ".env.example").read_text(encoding="utf-8"), re.M))
        self.assertEqual(used, {"VITE_SUPABASE_URL", "VITE_SUPABASE_ANON_KEY"})
        self.assertEqual(declared, used)
        self.assertTrue(used <= example, "every typed var must be documented in .env.example")
        self.assertNotRegex(decl, r"eyJ|service_role|https?://", "declaration file must not carry values")

    def test_tsconfig_include_covers_the_declaration(self):
        tsconfig = json.loads((self.out / "tsconfig.json").read_text(encoding="utf-8"))
        self.assertIn("src", tsconfig["include"])
        self.assertNotIn("types", tsconfig["compilerOptions"],
                         "fix must not narrow global @types via compilerOptions.types")

    @unittest.skipUnless(tsc_cmd(), "tsc not installed")
    def test_ts2339_reproduced_without_file_and_resolved_with_it(self):
        write_stubs(self.out)
        code, out = typecheck(self.out, ["src/lib/supabase.ts", VITE_ENV])
        self.assertEqual((code, out.strip()), (0, ""), "with fix: expected zero diagnostics")
        (self.out / VITE_ENV).unlink()
        code, out = typecheck(self.out, ["src/lib/supabase.ts"])
        self.assertNotEqual(code, 0)
        self.assertRegex(out, r"error TS2339: Property 'env' does not exist on type 'ImportMeta'",
                         "control: without the file the original defect must reappear")

    @unittest.skipUnless(tsc_cmd(), "tsc not installed")
    def test_declared_env_vars_are_typed_as_string(self):
        """The declarations are real types, not `any`: misusing a declared var is a type error."""
        write_stubs(self.out)
        probe = self.out / "src" / "probe.ts"
        probe.write_text("const u: string = import.meta.env.VITE_SUPABASE_URL;\nexport const x: number = u.length;\n"
                         "export const bad: number = import.meta.env.VITE_SUPABASE_URL;\n", encoding="utf-8")
        code, out = typecheck(self.out, ["src/probe.ts", VITE_ENV])
        self.assertIn("TS2322", out, "declared vars are typed as string (assigning to number must fail)")


if __name__ == "__main__":
    unittest.main()
